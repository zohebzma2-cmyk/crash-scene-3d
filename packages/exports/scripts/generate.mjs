// Reads design/tokens.css and the official logo (design/brand/insurifyai.svg) and
// writes src/tokens.ts and src/brand.ts. Run: npm run gen -w @csd/exports. A test fails if the
// checked-in files are stale, so the export code never carries its own copy of
// a color, size or icon path.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const out = fileURLToPath(new URL("../src/", import.meta.url));

export function buildTokensSource(css) {
  const decls = [...css.matchAll(/^\s*(--[a-z0-9-]+):\s*([^;]+);/gim)].map((m) => [m[1], m[2].replace(/\/\*.*?\*\//g, "").trim()]);
  const colors = {};
  const sizes = {};
  const raw = {};
  // light-dark(a, b) anywhere in a value -> a (balanced parens, top-level comma).
  const lightOf = (v) => {
    for (let i = v.indexOf("light-dark("); i >= 0; i = v.indexOf("light-dark(")) {
      let depth = 0, comma = -1, end = -1;
      for (let k = i + "light-dark".length; k < v.length; k++) {
        if (v[k] === "(") depth++;
        else if (v[k] === ")") { depth--; if (depth === 0) { end = k; break; } }
        else if (v[k] === "," && depth === 1 && comma < 0) comma = k;
      }
      if (comma < 0 || end < 0) throw new Error(`Unclosed light-dark( in tokens.css: ${v}`);
      v = v.slice(0, i) + v.slice(i + "light-dark(".length, comma).trim() + v.slice(end + 1);
    }
    return v;
  };
  for (const [name, value] of decls) {
    const v = lightOf(value);
    const key = name.slice(2);
    raw[key] = v;
    if (/^#[0-9a-f]{6}$/i.test(v)) colors[key] = v.toUpperCase();
    const rem = v.match(/^(-?[\d.]+)rem$/);
    const px = v.match(/^(-?[\d.]+)px$/);
    const inch = v.match(/^(-?[\d.]+)in$/);
    const num = v.match(/^-?[\d.]+$/);
    if (rem) sizes[key] = Number(rem[1]) * 16;
    else if (px) sizes[key] = Number(px[1]);
    else if (inch) sizes[key] = Number(inch[1]) * 96; // CSS px (96 per inch)
    else if (num) sizes[key] = Number(v);
  }
  const shadow = (name) => {
    const m = (raw[name] ?? "").match(/^(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+rgb\(\s*(\d+)\s+(\d+)\s+(\d+)\s*\/\s*([\d.]+)\s*\)$/);
    if (!m) throw new Error(`Can't read ${name} from tokens.css`);
    return { offsetXPx: Number(m[1]), offsetYPx: Number(m[2]), blurPx: Number(m[3]), color: `rgba(${m[4]},${m[5]},${m[6]},${m[7]})` };
  };
  const shadows = { sm: shadow("shadow-sm"), md: shadow("shadow-md") };
  const aspect = (name) => {
    const m = (raw[name] ?? "").match(/^(\d+)\s*\/\s*(\d+)$/);
    if (!m) throw new Error(`Can't read ${name}`);
    return Number(m[1]) / Number(m[2]);
  };
  const aspects = { pdfFig: aspect("aspect-pdf-fig"), pdfFigCompact: aspect("aspect-pdf-fig-compact") };
  const em = (name) => {
    const m = (raw[name] ?? "").match(/^(-?[\d.]+)em$/);
    if (!m) throw new Error(`Can't read ${name} (an em value) from tokens.css`);
    return Number(m[1]);
  };
  const logo = { markHeightEm: em("logo-mark-height"), gapEm: em("logo-gap") };
  const fonts = { sans: (raw["font-sans"].match(/^"([^"]+)"/) ?? [])[1], mono: (raw["font-mono"].match(/^"([^"]+)"/) ?? [])[1] };
  const body = (o) => JSON.stringify(o, null, 2);
  return `// GENERATED by packages/exports/scripts/generate.mjs from design/tokens.css. Do not edit.
// Colors are the light-mode values (exports are always light). Sizes are CSS px.
export const COLORS = ${body(colors)} as const;

export const SIZES = ${body(sizes)} as const;

export const SHADOWS = ${body(shadows)} as const;

export const ASPECTS = ${body(aspects)} as const;

export const LOGO = ${body(logo)} as const;

export const BRAND_FAMILIES = ${body(fonts)} as const;

export type ColorToken = keyof typeof COLORS;
export type SizeToken = keyof typeof SIZES;
`;
}

export function buildBrandSource(svg) {
  const g = svg.match(/<g transform="translate\(([\d.]+) ([\d.]+)\) scale\(([\d.]+)\)">/);
  const p = svg.match(/<path fill="#[0-9A-Fa-f]{6}" fill-rule="evenodd" d="([^"]+)"\/>/);
  if (!g || !p) throw new Error("design/brand/insurifyai.svg is not one path in one translate/scale group");
  const nums = [...p[1].matchAll(/[ML]\s*(-?[\d.]+)\s+(-?[\d.]+)/g)].map((m) => [Number(m[1]), Number(m[2])]);
  const xs = nums.map((n) => n[0]);
  const ys = nums.map((n) => n[1]);
  const bounds = { minX: Math.min(...xs), minY: Math.min(...ys), maxX: Math.max(...xs), maxY: Math.max(...ys) };
  return `// GENERATED by packages/exports/scripts/generate.mjs from design/brand/insurifyai.svg. Do not edit.
// The official InsurifyAI mark, exactly as supplied: one even-odd path in a translate/scale group.
// The fill is --color-logo (COLORS["color-logo"]); a test checks it equals the SVG's fill.
export const MARK_PATH_D = ${JSON.stringify(p[1])};
export const MARK_TRANSLATE = [${g[1]}, ${g[2]}] as const;
export const MARK_SCALE = ${g[3]};
/** Bounds of the path in its own coordinates (before the transform). */
export const MARK_BOUNDS = ${JSON.stringify(bounds)} as const;
`;
}

export function generate() {
  const css = readFileSync(`${root}design/tokens.css`, "utf8");
  const svg = readFileSync(`${root}design/brand/insurifyai.svg`, "utf8");
  return { "tokens.ts": buildTokensSource(css), "brand.ts": buildBrandSource(svg) };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const [name, text] of Object.entries(generate())) writeFileSync(`${out}${name}`, text);
  console.log("wrote src/tokens.ts and src/brand.ts");
}
